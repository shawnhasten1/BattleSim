/**
 * Which game-icons.net icon each SRD monster's placeholder token shows.
 *
 * Values are `"<author>/<icon>"`: the icon's name in `@iconify-json/game-icons` and the
 * contributor folder it comes from in github.com/game-icons/icons. The author is what the
 * CC BY 3.0 credit names ("Icons made by …"), so it must be the author of the version the
 * iconify package ships. A few names exist under two authors (bat, cobra, cultist: Skoll;
 * dragon-head, fairy, horse-head, ram, rock: Lorc); check the path data against the GitHub
 * SVG before changing one of those.
 *
 * Every slug in the monster index needs an entry: dragons come from `DRAGON_*` below, the rest
 * from `MONSTER_ICONS`. `npm run srd:tokens` fails on a missing one.
 */

/** A true dragon's age picks its icon; its colour picks the token's disc. */
export const DRAGON_AGE_ICONS: Record<string, string> = {
  wyrmling: "lorc/sea-dragon",
  young: "lorc/dragon-breath",
  adult: "lorc/dragon-head",
  ancient: "delapouite/spiked-dragon-head"
};

export const DRAGON_COLORS: Record<string, string> = {
  black: "#2a2a2e",
  blue: "#2b5fb8",
  green: "#2f7a3a",
  red: "#a8231c",
  white: "#d9e2ea",
  brass: "#b08436",
  bronze: "#8a5a2c",
  copper: "#a9603b",
  gold: "#c99a24",
  silver: "#9aa6b1"
};

/** `ancient-red-dragon` / `red-dragon-wyrmling` → its age and colour. */
export function parseDragonSlug(slug: string): { age: string; color: string } | undefined {
  const wyrmling = /^([a-z]+)-dragon-wyrmling$/.exec(slug);
  if (wyrmling && DRAGON_COLORS[wyrmling[1]!]) return { age: "wyrmling", color: wyrmling[1]! };
  const grown = /^(young|adult|ancient)-([a-z]+)-dragon$/.exec(slug);
  if (grown && DRAGON_COLORS[grown[2]!]) return { age: grown[1]!, color: grown[2]! };
  return undefined;
}

